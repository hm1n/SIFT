/**
 * 하루 상한입니다. 근거는 `llm-wiki/wiki/2026-09-02-LLM-비용-산정.md`의 회당 비용입니다. 분석 한 번이
 * 최대 0.03833달러이므로 3회면 한 사람이 하루에 쓸 수 있는 돈이 0.115달러로 묶입니다. 예산 10달러를
 * 한 사람이 혼자 비우려면 87일이 걸리고, 그 사이에 사용량 알림이 도착할 시간이 생깁니다.
 *
 * 같은 저장소를 다시 열면 저장된 분석을 그대로 그리고 모델을 부르지 않으므로(`openRepository`),
 * 3회는 새 저장소 셋을 분석하거나 "다시 분석"을 세 번 누르는 것을 뜻합니다. 정상 사용에서는 거의
 * 닿지 않습니다.
 */
export const DAILY_ANALYSIS_LIMIT = 3;

const DAY_MS = 86_400_000;

/**
 * 초기화 기준 시간대입니다. 한국 표준시 자정에 횟수가 다시 0이 됩니다.
 *
 * 데이터베이스의 `current_date`를 쓰지 않습니다. Neon은 UTC로 돌기 때문에 그 값으로 날짜를 가르면
 * 한국 시간 오전 9시에 횟수가 초기화됩니다. 화면이 "내일 다시 할 수 있습니다"라고 말하는 순간과
 * 실제로 풀리는 순간이 갈리면 안내가 틀린 말이 됩니다.
 */
const KST_OFFSET_MS = 9 * 60 * 60 * 1000;

/**
 * 이 시각이 속한 한국 날짜입니다. `2026-09-22` 모양이고 표의 `usage_date` 칸으로 그대로 갑니다.
 *
 * `toLocaleDateString`에 시간대를 넘기는 방법을 쓰지 않습니다. 그 함수는 실행 환경의 ICU 자료에
 * 기대는데, 서버리스 런타임마다 자료가 달라 같은 입력에 다른 문자열이 나올 수 있습니다. 고정
 * 시차를 더하고 잘라 내면 어디서 돌아도 같은 값이 나옵니다.
 */
export function analysisUsageDate(now: number = Date.now()): string {
  return new Date(now + KST_OFFSET_MS).toISOString().slice(0, 10);
}

/**
 * 그 한국 날짜의 횟수가 풀리는 시각입니다. 다음 한국 자정이고 UTC 기준 `Date`로 돌려줍니다.
 *
 * 화면이 "언제 다시 할 수 있는지"를 그리는 값이라 상한을 검사한 라우트가 응답에 실어 보냅니다.
 * 화면이 스스로 계산하면 서버가 쓴 날짜 기준과 어긋날 수 있습니다.
 */
export function analysisQuotaResetAt(usageDate: string): Date {
  return new Date(Date.parse(`${usageDate}T00:00:00Z`) + DAY_MS - KST_OFFSET_MS);
}
